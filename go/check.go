package jostraca

// HOLD A COMMITTED TREE TO WHAT THE GENERATORS PRODUCE (twin of
// ts/src/check.ts).
//
//	res, err := jostraca.New().Check(jostraca.Options{Folder: "app"}, root)
//	if len(res.Drift) > 0 { /* the tree is stale */ }
//
// Generate into memory, compare with the folder, and answer with the
// difference as DATA. It is the CI half of generating: a generator is
// run, its output is committed and reviewed, and the question a build
// asks from then on is whether the two still agree.
//
// A GENERATION MODE, NOT A TOOL. Mem, the existing-file modes and the
// dry run are all options on Generate, and this belongs beside them:
// every generator wants this gate, whether it is written in Go at the
// call site or arrives as a component tree from another language.
//
// The shadow, what it buys and what it costs, are the same on both
// sides and the TypeScript file carries the long form. In brief: the
// folder is invisible to the run, so nothing committed can change what
// the generators produce; every write goes to memory, so a check
// changes nothing; reads outside the folder fall through, so a Fragment
// or CopyFiles source is read as it would be; and Inject, which rewrites
// a file that already exists, is the one component the shadow cannot
// serve.

import (
	"bytes"
	"io/fs"
	"path"
	"path/filepath"
	"sort"
	"strings"
)

// DriftKind says which question a file failed.
type DriftKind string

const (
	// DriftMissing: the generators claim it and the folder does not
	// hold it.
	DriftMissing DriftKind = "missing"

	// DriftContent: the bytes differ.
	DriftContent DriftKind = "content"

	// DriftMode: the bytes match and the permission bits do not, where
	// the tree stated them with FileProps.Mode.
	DriftMode DriftKind = "mode"
)

// Drift is one way a committed file differs from what the generators
// produce. The bytes are carried rather than rendered: a build wants an
// exit code, a test wants an assertion, a reviewer wants hunks.
type Drift struct {
	// Path relative to the checked folder, forward slashes.
	Path string

	Kind DriftKind

	// What the generators produce. Always set -- a missing file still
	// has generated bytes, which is what would be written.
	Generated []byte

	// What the folder holds. Nil when Kind is DriftMissing.
	Existing []byte

	// The mode the tree declared, and the bits on disk. Both set only
	// when Kind is DriftMode.
	Mode         fs.FileMode
	ExistingMode fs.FileMode
}

// CheckResult is what Check answers.
type CheckResult struct {
	// The folder that was checked, as given.
	Folder string

	// Every path compared, relative and sorted. A file the generators
	// do not claim is not here.
	Checked []string

	// Sorted by path. Empty means the folder is what the generators
	// produce.
	Drift []Drift

	// The run report of the generate that produced the comparison.
	Files Files
}

// jostraca's own bookkeeping under the output folder. Timestamped, so
// never byte-stable, and never part of what a generator claims.
const checkMetaFolder = ".jostraca"

// shadowFS is memory under `root`, `base` outside it.
//
// `base` is the filesystem holding the committed tree. Keeping it a
// field rather than reaching for OsFS is what lets a test check one
// in-memory tree against another without touching disk.
//
// `modes` records A MODE THE RUN ACTUALLY ASKED FOR. The volume cannot
// answer that on its own, because it gives every file a default mode,
// so "what is this file's mode in memory" does not distinguish a File
// that stated one from a File that said nothing. The narrower question
// is only visible here, where the file handler passes it.
type shadowFS struct {
	mem   *MemFS
	base  FS
	root  string
	modes map[string]fs.FileMode
}

func newShadowFS(base FS, root string) *shadowFS {
	return &shadowFS{
		mem:   NewMemFS(),
		base:  base,
		root:  root,
		modes: map[string]fs.FileMode{},
	}
}

// resolve is p as the volume keys it: absolute, against the working
// directory when the run hands over a relative path. The run keeps the
// folder as the caller gave it, so its reported paths match a plain
// Generate, and the volume and root stay absolute.
func (s *shadowFS) resolve(p string) string { return shadowKey(p) }

// shadowKey is resolve without a shadow, so the root is keyed by the same
// rule as every path under it. filepath.Abs alone would not do: on Windows
// it gives `/app` a drive, and the volume keys `/app` as written.
func shadowKey(p string) string {
	if !strings.HasPrefix(filepath.ToSlash(p), "/") && !filepath.IsAbs(p) {
		if abs, err := filepath.Abs(filepath.FromSlash(p)); err == nil {
			p = abs
		}
	}
	return memClean(p)
}

// under reports whether a resolved path is at or below root, on a path
// BOUNDARY: `/out2/a` is not under `/out`, however much of the string it
// shares.
func (s *shadowFS) under(rp string) bool {
	return rp == s.root || strings.HasPrefix(rp, s.root+"/")
}

// pick routes a READ: memory inside the folder, base outside it. It
// returns the path to hand that filesystem.
func (s *shadowFS) pick(p string) (FS, string) {
	if rp := s.resolve(p); s.under(rp) {
		return s.mem, rp
	}
	return s.base, p
}

func (s *shadowFS) ReadFile(p string) ([]byte, error) {
	f, fp := s.pick(p)
	return f.ReadFile(fp)
}

func (s *shadowFS) Exists(p string) bool {
	f, fp := s.pick(p)
	return f.Exists(fp)
}

func (s *shadowFS) Stat(p string) (FileInfo, error) {
	f, fp := s.pick(p)
	return f.Stat(fp)
}

func (s *shadowFS) ReadDir(p string) ([]DirEntry, error) {
	f, fp := s.pick(p)
	return f.ReadDir(fp)
}

// EVERY WRITE GOES TO MEMORY, including one aimed outside the folder. A
// command that only asks a question must not be able to answer it by
// changing something.
func (s *shadowFS) WriteFile(p string, data []byte) error {
	return s.mem.WriteFile(s.resolve(p), data)
}

func (s *shadowFS) MkdirAll(p string) error { return s.mem.MkdirAll(s.resolve(p)) }
func (s *shadowFS) Remove(p string) error   { return s.mem.Remove(s.resolve(p)) }

// The atomic write lands under a temp name and is renamed into place,
// so a declared mode follows the bytes to their final path.
func (s *shadowFS) Rename(oldpath, newpath string) error {
	from, to := s.resolve(oldpath), s.resolve(newpath)
	if mode, held := s.modes[from]; held {
		s.modes[to] = mode
		delete(s.modes, from)
	}
	return s.mem.Rename(from, to)
}

// Chmod is where a declared mode becomes visible, and implementing it
// is the whole reason the shadow is a type rather than a MemFS: the
// file handler feature-detects chmodFS, and MemFS does not implement
// it, so a memory run would never be asked about a mode at all.
//
// RECORDED, NOT APPLIED. There is nothing in the volume to apply it to
// -- MemFS keeps no modes -- and the record is what the comparison
// needs. The handler calls this on the TEMP path with an explicit mode,
// and Rename carries the record to the final path.
//
// A File that states NO mode does not reach here: the handler's other
// arm chmods to the existing target's mode, and under the shadow the
// target does not exist, so nothing is declared. That is what keeps a
// silent File held to nothing.
func (s *shadowFS) Chmod(p string, mode fs.FileMode) error {
	s.modes[s.resolve(p)] = mode & fs.ModePerm
	return nil
}

// generated walks what the run produced, by path relative to root.
func (s *shadowFS) generated() map[string][]byte {
	out := map[string][]byte{}

	var walk func(dir, rel string)
	walk = func(dir, rel string) {
		entries, err := s.mem.ReadDir(dir)
		if err != nil {
			// Nothing was generated under it, which is not an error: an
			// empty tree is a clean check against an empty claim.
			return
		}
		for _, e := range entries {
			key := e.Name
			if rel != "" {
				key = rel + "/" + e.Name
			}
			if key == checkMetaFolder ||
				strings.HasPrefix(key, checkMetaFolder+"/") {
				continue
			}
			full := dir + "/" + e.Name
			if e.IsDir {
				walk(full, key)
				continue
			}
			data, err := s.mem.ReadFile(full)
			if err != nil {
				continue
			}
			out[key] = data
		}
	}

	walk(s.root, "")
	return out
}

// Check runs Generate against a shadowed folder and compares.
//
// It takes the same Options as Generate; Folder is the folder checked.
// FS, if set, is the filesystem holding the committed tree.
func (j *J) Check(opts Options, root func(*J)) (CheckResult, error) {
	folder := opts.Folder
	if folder == "" {
		folder = j.st.opts.Folder
	}
	if folder == "" {
		folder = "."
	}

	var base FS = opts.FS
	if base == nil {
		base = j.st.opts.FS
	}
	if base == nil {
		base = OsFS{}
	}

	// The ROOT is resolved, because "" is not a usable root.
	// `memClean(".")` is the empty string, and against it `under` answers
	// backwards -- a relative output path is not "under" it, so the run
	// would read the COMMITTED file and a protected one would suppress
	// its own write; an absolute path from a Project.Folder elsewhere is,
	// so the walk would descend into a tree outside the folder.
	//
	// The RUN keeps the folder as given, so Files reports the paths a
	// plain Generate reports, as in TypeScript. The shadow resolves each
	// relative path it is handed against the working directory, which is
	// what TypeScript's memfs does with the same paths.
	shadow := newShadowFS(base, shadowKey(folder))

	run := opts
	run.Folder = folder
	run.FS = shadow

	// Forced, because each would answer a different question than the
	// one asked. NoDuplicate off would write a `.jostraca/generated`
	// baseline for a later merge, and a check makes no next run to
	// merge into; a dry run would write nothing to the volume, leaving
	// nothing to compare; Build false never reaches the file handler.
	// Applied AFTER the merge, because a per-call false cannot clear a
	// global true.
	res, err := j.generate(run, root, func(o *Options) {
		o.Control.NoDuplicate = true
		o.Control.Dryrun = false
		build := true
		o.Build = &build
	})
	if err != nil {
		return CheckResult{}, err
	}

	files := shadow.generated()

	checked := make([]string, 0, len(files))
	for p := range files {
		checked = append(checked, p)
	}
	sort.Strings(checked)

	out := CheckResult{
		Folder:  folder,
		Checked: checked,
		Files:   res.Files,
	}

	for _, p := range checked {
		gen := files[p]
		at := path.Join(folder, p)

		have, rerr := base.ReadFile(at)
		if rerr != nil {
			out.Drift = append(out.Drift, Drift{
				Path: p, Kind: DriftMissing, Generated: gen,
			})
			continue
		}

		if !bytes.Equal(gen, have) {
			out.Drift = append(out.Drift, Drift{
				Path: p, Kind: DriftContent, Generated: gen, Existing: have,
			})
			continue
		}

		// A MODE IS OUTPUT TOO, where the tree declared one. A file
		// with the right bytes and the wrong bits is drift no byte
		// comparison can see: a run would chmod it and the gate would
		// have said clean. A File that says nothing about mode leaves
		// whatever is there, so there is nothing to hold it to.
		mode, declared := shadow.modes[memClean(path.Join(shadow.root, p))]
		if !declared {
			continue
		}
		info, serr := base.Stat(at)
		if serr != nil {
			continue
		}
		if info.Mode&fs.ModePerm != mode&fs.ModePerm {
			out.Drift = append(out.Drift, Drift{
				Path: p, Kind: DriftMode, Generated: gen, Existing: have,
				Mode: mode & fs.ModePerm, ExistingMode: info.Mode & fs.ModePerm,
			})
		}
	}

	return out, nil
}
