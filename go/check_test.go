// THE CHECK GENERATION MODE (check.go, twin of ts/src/check.ts).
//
// MOSTLY IN MEMORY, which is the point: the folder a check runs against
// is read through Options.FS, so a test can hold one in-memory tree
// against another and never touch disk.

// checkMem checks a generator against a committed tree, both in memory.
func checkMem(
	t *testing.T,
	committed map[string][]byte,
	root func(*J),
) CheckResult {
	t.Helper()
	base := NewMemFS()
	for p, data := range committed {
		if err := base.MkdirAll(filepath.ToSlash(filepath.Dir(p))); err != nil {
			t.Fatal(err)
		}
		if err := base.WriteFile(p, data); err != nil {
			t.Fatal(err)
		}
	}
	res, err := New(WithNow(func() int64 { return 1 })).
		Check(Options{Folder: "/app", FS: base}, root)
	if err != nil {
		t.Fatal(err)
	}
	return res
}

// A FOLDER THAT MATCHES IS CLEAN, and Checked says what was compared.
func TestCheckMatchingFolderIsClean(t *testing.T) {
	res := checkMem(t, map[string][]byte{
		"/app/a.txt":     []byte("A\n"),
		"/app/sub/b.txt": []byte("B\n"),
	}, func(j *J) {
		j.File("a.txt", func(j *J) { j.Content("A\n") })
		j.Folder("sub", func(j *J) {
			j.File("b.txt", func(j *J) { j.Content("B\n") })
		})
	})

	if len(res.Drift) != 0 {
		t.Fatalf("drift: %+v", res.Drift)
	}
	if strings.Join(res.Checked, ",") != "a.txt,sub/b.txt" {
		t.Fatalf("checked: %v", res.Checked)
	}
	if res.Folder != "/app" {
		t.Fatalf("folder: %q", res.Folder)
	}
}

// THE DIFFERENCE COMES BACK AS DATA: both sides' bytes, per path.
func TestCheckDriftIsData(t *testing.T) {
	res := checkMem(t, map[string][]byte{
		"/app/same.txt":   []byte("S\n"),
		"/app/edited.txt": []byte("EDITED\n"),
	}, func(j *J) {
		j.File("same.txt", func(j *J) { j.Content("S\n") })
		j.File("edited.txt", func(j *J) { j.Content("GENERATED\n") })
		j.File("absent.txt", func(j *J) { j.Content("NEW\n") })
	})

	if len(res.Drift) != 2 {
		t.Fatalf("drift: %+v", res.Drift)
	}

	// Sorted by path.
	if res.Drift[0].Path != "absent.txt" || res.Drift[0].Kind != DriftMissing {
		t.Fatalf("first: %+v", res.Drift[0])
	}
	if string(res.Drift[0].Generated) != "NEW\n" || res.Drift[0].Existing != nil {
		t.Fatalf("missing carries generated bytes only: %+v", res.Drift[0])
	}

	if res.Drift[1].Path != "edited.txt" || res.Drift[1].Kind != DriftContent {
		t.Fatalf("second: %+v", res.Drift[1])
	}
	if string(res.Drift[1].Generated) != "GENERATED\n" ||
		string(res.Drift[1].Existing) != "EDITED\n" {
		t.Fatalf("content carries both sides: %+v", res.Drift[1])
	}
}

