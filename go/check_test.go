// THE COMMITTED TREE CANNOT CHANGE WHAT THE GENERATORS PRODUCE, which
// is what the shadow is for. Exclude is the sharpest demonstration: on
// a real generate it means "leave this file alone if it already
// exists", so the file is never written and never compared.
func TestCheckCommittedTreeCannotInfluenceTheRun(t *testing.T) {
	gen := func(j *J) {
		j.FileP(FileProps{Name: "a.txt", Exclude: true}, func(j *J) {
			j.Content("GENERATED\n")
		})
	}

	res := checkMem(t, map[string][]byte{"/app/a.txt": []byte("STALE\n")}, gen)
	if len(res.Drift) != 1 || res.Drift[0].Kind != DriftContent {
		t.Fatalf("drift: %+v", res.Drift)
	}
	if string(res.Drift[0].Generated) != "GENERATED\n" ||
		string(res.Drift[0].Existing) != "STALE\n" {
		t.Fatalf("sides: %+v", res.Drift[0])
	}

	// The control: a plain generate DOES leave it alone.
	base := NewMemFS()
	_ = base.MkdirAll("/app")
	_ = base.WriteFile("/app/a.txt", []byte("STALE\n"))
	if _, err := New(WithNow(func() int64 { return 1 })).
		Generate(Options{Folder: "/app", FS: base}, gen); err != nil {
		t.Fatal(err)
	}
	got, _ := base.ReadFile("/app/a.txt")
	if string(got) != "STALE\n" {
		t.Fatalf("a plain generate should have left it: %q", got)
	}
}

