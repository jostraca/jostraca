package jostraca

import (
	"strings"
	"unicode"
	"unicode/utf8"
)

// jsToUpper is JavaScript's String.prototype.toUpperCase: the simple case
// mapping, plus SpecialCasing's unconditional mappings to more than one
// character (sharp s to SS, the ff ligature to FF, and so on), which Go's
// unicode.ToUpper does not apply.
//
// Go's unicode tables and Node's ICU can differ by Unicode version for
// characters assigned since, which is a documented residual.
func jsToUpper(s string) string {
	if isASCII(s) {
		return strings.ToUpper(s)
	}
	var sb strings.Builder
	sb.Grow(len(s))
	for _, r := range s {
		if m, ok := jsUpperSpecial[r]; ok {
			for _, x := range m {
				sb.WriteRune(x)
			}
			continue
		}
		sb.WriteRune(unicode.ToUpper(r))
	}
	return sb.String()
}

// jsToLower is JavaScript's String.prototype.toLowerCase: the simple case
// mapping, dotted capital I to i + U+0307, and capital sigma to final
// sigma where Unicode's Final_Sigma condition holds.
func jsToLower(s string) string {
	if isASCII(s) {
		return strings.ToLower(s)
	}
	var sb strings.Builder
	sb.Grow(len(s))
	for i, r := range s {
		switch r {
		case 0x0130:
			sb.WriteString("i\u0307")
		case 0x03A3:
			if jsFinalSigma(s, i) {
				sb.WriteRune(0x03C2)
			} else {
				sb.WriteRune(0x03C3)
			}
		default:
			sb.WriteRune(unicode.ToLower(r))
		}
	}
	return sb.String()
}

func isASCII(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] >= utf8.RuneSelf {
			return false
		}
	}
	return true
}

// jsFinalSigma is Unicode's Final_Sigma condition for the sigma at byte
// offset i: preceded by a cased letter (skipping case-ignorable
// characters), and not followed by one.
func jsFinalSigma(s string, i int) bool {
	before := false
	for j := i; j > 0; {
		r, n := utf8.DecodeLastRuneInString(s[:j])
		j -= n
		if jsCaseIgnorable(r) {
			continue
		}
		before = jsCased(r)
		break
	}
	if !before {
		return false
	}
	for _, r := range s[i+utf8.RuneLen(0x03A3):] {
		if jsCaseIgnorable(r) {
			continue
		}
		return !jsCased(r)
	}
	return true
}

func jsCased(r rune) bool {
	return unicode.IsUpper(r) || unicode.IsLower(r) || unicode.IsTitle(r) ||
		unicode.Is(unicode.Other_Lowercase, r) || unicode.Is(unicode.Other_Uppercase, r)
}

func jsCaseIgnorable(r rune) bool {
	switch r {
	case 0x0027, 0x002E, 0x003A, 0x00B7, 0x0387, 0x055F, 0x05F4, 0x2018, 0x2019,
		0x2024, 0x2027, 0xFE13, 0xFE52, 0xFE55, 0xFF07, 0xFF0E, 0xFF1A:
		return true
	}
	return unicode.In(r, unicode.Mn, unicode.Me, unicode.Cf, unicode.Lm, unicode.Sk)
}

